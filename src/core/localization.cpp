UiLanguage ui_language_from_code(LanguageCode code) {
    if (code == pack_language_code("zh-Hans") || code == pack_language_code("zh-CN")) {
        return UiLanguage::ZhHans;
    }
    if (code == pack_language_code("zh-Hant") || code == pack_language_code("zh-TW")) {
        return UiLanguage::ZhHant;
    }
    return UiLanguage::En;
}

