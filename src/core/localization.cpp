UiLanguage ui_language_from_code(LanguageCode code) {
    struct UiMapping {
        LanguageCode code;
        UiLanguage ui;
    };
    static constexpr UiMapping kMappings[] = {
        {pack_language_code("zh-Hans"), UiLanguage::ZhHans},
        {pack_language_code("zh-CN"), UiLanguage::ZhHans},
        {pack_language_code("zh-Hant"), UiLanguage::ZhHant},
        {pack_language_code("zh-TW"), UiLanguage::ZhHant},
        {pack_language_code("ja"), UiLanguage::Ja},
        {pack_language_code("ko"), UiLanguage::Ko},
        {pack_language_code("fr"), UiLanguage::Fr},
        {pack_language_code("fr-CA"), UiLanguage::Fr},
        {pack_language_code("de"), UiLanguage::De},
        {pack_language_code("it"), UiLanguage::It},
        {pack_language_code("es"), UiLanguage::Es},
        {pack_language_code("es-419"), UiLanguage::Es},
        {pack_language_code("nl"), UiLanguage::Nl},
        {pack_language_code("pt"), UiLanguage::Pt},
        {pack_language_code("pt-BR"), UiLanguage::Pt},
        {pack_language_code("ru"), UiLanguage::Ru},
        {pack_language_code("pl"), UiLanguage::Pl},
        {pack_language_code("th"), UiLanguage::Th},
        {pack_language_code("en-US"), UiLanguage::En},
        {pack_language_code("en-GB"), UiLanguage::En},
    };
    for (const auto& entry : kMappings) {
        if (entry.code == code) {
            return entry.ui;
        }
    }
    return UiLanguage::En;
}

